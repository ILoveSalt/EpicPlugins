package hgds.epicgrief;

import org.bukkit.command.Command;
import org.bukkit.command.CommandExecutor;
import org.bukkit.command.CommandSender;
import org.bukkit.command.TabCompleter;
import org.bukkit.entity.Player;

import java.util.Collections;
import java.util.List;

public final class MessageToggleCommand implements CommandExecutor, TabCompleter {
    private final EpicChat plugin;

    public MessageToggleCommand(EpicChat plugin) {
        this.plugin = plugin;
    }

    @Override
    public boolean onCommand(CommandSender sender, Command command, String label, String[] args) {
        if (!(sender instanceof Player)) {
            sender.sendMessage("Only players can use this command.");
            return true;
        }
        Player player = (Player) sender;
        boolean enabled = plugin.togglePrivateMessages(player);
        plugin.sendConfiguredMessage(player, enabled ? "MESSAGE_ON" : "MESSAGE_OFF");
        return true;
    }

    @Override
    public List<String> onTabComplete(CommandSender sender, Command command, String alias, String[] args) {
        return Collections.emptyList();
    }
}
